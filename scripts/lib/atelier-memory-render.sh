vault_render_index_note() { # <target_file>
  local out_file="$1"
  local p_rows
  p_rows="$(printf "SELECT DISTINCT hex(project) FROM records ORDER BY project;" | sqlro 2>/dev/null)"

  render_type_list() { # <heading> <type>
    local heading="$1" type="$2" rows
    rows="$(printf "SELECT id || '|' || hex(title) FROM records WHERE type='%s' AND superseded_by IS NULL ORDER BY created_at DESC, rowid DESC;" "$type" | sqlro 2>/dev/null)"
    printf '\n## %s\n' "$heading"
    if [ -z "$rows" ]; then
      printf -- '- (none)\n'
      return
    fi
    local line id hex_t t
    while IFS= read -r line; do
      [ -n "$line" ] || continue
      id="${line%%|*}"
      hex_t="${line#*|}"
      t="$(dec "$hex_t" | tr '\r\n' ' ')"
      printf -- '- [[%s]]: %s\n' "$id" "$t"
    done <<<"$rows"
  }

  {
    printf '%s\n\n' "$BANNER"
    printf '# %s\n\n' "$H_INDEX_TITLE"
    printf '## %s\n' "$H_PROJECTS"
    if [ -z "$p_rows" ]; then
      printf -- '- (none)\n'
    else
      local hex_p raw_p pslug
      while IFS= read -r hex_p; do
        [ -n "$hex_p" ] || continue
        raw_p="$(dec "$hex_p")"
        pslug="$(slug_safe_project "$raw_p")"
        printf -- '- [[%s]]\n' "$pslug"
      done <<<"$p_rows"
    fi

    render_type_list "$H_REQUESTS" "request"
    render_type_list "$H_QUESTIONS" "question"
    render_type_list "$H_DECISIONS" "decision"
    render_type_list "$H_FACTS" "fact"
    render_type_list "$H_HELD" "held"
    render_type_list "$H_DIGESTS" "digest"
  } > "$out_file"
}

# ---------- Full Render ----------

vault_render_full() {
  local cli_vault="${1:-}"
  if ! vault_is_enabled "$cli_vault"; then
    echo "atelier-memory: vault render disabled" >&2
    return 0
  fi

  local VAULT lang
  VAULT="$(vault_dir_resolve "$cli_vault")"
  lang="$(vault_get_lang)"
  vault_init_lang_tables "$lang"

  local VAULT_PARENT TMP_DIR
  VAULT_PARENT="$(dirname "$VAULT")"
  mkdir -p "$VAULT_PARENT" "$VAULT" || return 1
  TMP_DIR="$(mktemp -d "${VAULT_PARENT}/.atelier-vault-tmp.XXXXXX")" || return 1

  mkdir -p "$TMP_DIR/$DIR_PROJECTS" "$TMP_DIR/$DIR_RECORDS" "$TMP_DIR/$DIR_ISSUES" "$TMP_DIR/$DIR_PRS"

  # Render index note into TMP_DIR
  vault_render_index_note "$TMP_DIR/$INDEX_FILE"

  if [ -f "$DB" ]; then
    # Render all records into TMP_DIR
    local rec_ids id
    rec_ids="$(printf "SELECT id FROM records ORDER BY rowid;" | sqlro 2>/dev/null)"
    if [ -n "$rec_ids" ]; then
      while IFS= read -r id; do
        [ -n "$id" ] || continue
        vault_render_record_note "$id" "$TMP_DIR/$DIR_RECORDS/$id.md"
      done <<<"$rec_ids"
    fi

    # Render all project notes into TMP_DIR
    local p_rows hex_p raw_p pslug
    p_rows="$(printf "SELECT DISTINCT hex(project) FROM records;" | sqlro 2>/dev/null)"
    if [ -n "$p_rows" ]; then
      while IFS= read -r hex_p; do
        [ -n "$hex_p" ] || continue
        raw_p="$(dec "$hex_p")"
        pslug="$(slug_safe_project "$raw_p")"
        vault_render_project_note "$raw_p" "$TMP_DIR/$DIR_PROJECTS/$pslug.md"
      done <<<"$p_rows"
    fi

    # Render all issue / PR stub notes into TMP_DIR
    local all_refs ref val slug
    all_refs="$(printf "SELECT hex(refs) FROM records WHERE refs IS NOT NULL AND refs != '[]';" | sqlro 2>/dev/null | while read -r line; do dec "$line"; printf '\n'; done | jq -r '.[]?' 2>/dev/null | sort -u)"
    if [ -n "$all_refs" ]; then
      while IFS= read -r ref; do
        [ -n "$ref" ] || continue
        case "$ref" in
          issue:*)
            val="${ref#issue:}"
            slug="$(slug_safe_ref "$val")"
            vault_render_issue_stub "$val" "$TMP_DIR/$DIR_ISSUES/$slug.md"
            ;;
          pr:*)
            val="${ref#pr:}"
            slug="$(slug_safe_ref "$val")"
            vault_render_pr_stub "$val" "$TMP_DIR/$DIR_PRS/$slug.md"
            ;;
        esac
      done <<<"$all_refs"
    fi
  fi

  # Language change detection & migration
  if vault_read_marker "$VAULT"; then
    # 1. Move old inbox contents to new inbox
    if [ -n "$MARKER_INBOX" ] && [ "$MARKER_INBOX" != "$DIR_INBOX" ] && [ -d "$VAULT/$MARKER_INBOX" ]; then
      mkdir -p "$VAULT/$DIR_INBOX"
      find "$VAULT/$MARKER_INBOX" -mindepth 1 -maxdepth 1 -exec mv -f {} "$VAULT/$DIR_INBOX"/ \; 2>/dev/null || true
      rmdir "$VAULT/$MARKER_INBOX" 2>/dev/null || true
    fi

    # 2. Clean old index if name changed
    if [ -n "$MARKER_INDEX" ] && [ "$MARKER_INDEX" != "$INDEX_FILE" ] && [ -f "$VAULT/$MARKER_INDEX" ]; then
      if is_atelier_file "$VAULT/$MARKER_INDEX"; then
        rm -f "$VAULT/$MARKER_INDEX"
      else
        echo "atelier-memory: leaving operator file in place: $VAULT/$MARKER_INDEX" >&2
      fi
    fi

    # 3. Clean old generated folders if names changed
    clean_old_dir() {
      local old_d="$1" new_target="$2"
      [ -n "$old_d" ] || return 0
      [ -d "$VAULT/$old_d" ] || return 0
      local f fbase
      for f in "$VAULT/$old_d"/*; do
        [ -e "$f" ] || continue
        if is_atelier_file "$f"; then
          rm -f "$f"
        else
          echo "atelier-memory: leaving operator file in place: $f" >&2
          fbase="$(basename "$f")"
          cp -p "$f" "$TMP_DIR/$new_target/$fbase"
          rm -f "$f"
        fi
      done
      rmdir "$VAULT/$old_d" 2>/dev/null || true
    }

    [ "$MARKER_PROJECTS" != "$DIR_PROJECTS" ] && clean_old_dir "$MARKER_PROJECTS" "$DIR_PROJECTS"
    [ "$MARKER_RECORDS" != "$DIR_RECORDS" ] && clean_old_dir "$MARKER_RECORDS" "$DIR_RECORDS"
    [ "$MARKER_ISSUES" != "$DIR_ISSUES" ] && clean_old_dir "$MARKER_ISSUES" "$DIR_ISSUES"
    [ "$MARKER_PRS" != "$DIR_PRS" ] && clean_old_dir "$MARKER_PRS" "$DIR_PRS"
  fi

  # Swap each generated directory into $VAULT safely
  swap_folder() {
    local dir_name="$1"
    local target="$VAULT/$dir_name" staged="$TMP_DIR/$dir_name"
    if [ -d "$target" ]; then
      local f fbase
      for f in "$target"/*; do
        [ -e "$f" ] || continue
        if ! is_atelier_file "$f"; then
          echo "atelier-memory: leaving operator file in place: $f" >&2
          fbase="$(basename "$f")"
          cp -p "$f" "$staged/$fbase"
        fi
      done
      local swap_tmp
      swap_tmp="$(mktemp -d "${VAULT_PARENT}/.atelier-vault-swap.XXXXXX")"
      mv "$target" "$swap_tmp/old"
      mv "$staged" "$target"
      rm -rf "$swap_tmp"
    else
      mv "$staged" "$target"
    fi
  }

  swap_folder "$DIR_PROJECTS"
  swap_folder "$DIR_RECORDS"
  swap_folder "$DIR_ISSUES"
  swap_folder "$DIR_PRS"

  # Swap index note
  if [ -f "$VAULT/$INDEX_FILE" ]; then
    if is_atelier_file "$VAULT/$INDEX_FILE"; then
      mv -f "$TMP_DIR/$INDEX_FILE" "$VAULT/$INDEX_FILE"
    else
      echo "atelier-memory: leaving operator file in place: $VAULT/$INDEX_FILE" >&2
    fi
  else
    mv -f "$TMP_DIR/$INDEX_FILE" "$VAULT/$INDEX_FILE"
  fi

  # Ensure inbox folder exists empty if not present
  mkdir -p "$VAULT/$DIR_INBOX"

  # Write marker file
  vault_write_marker "$VAULT" "$lang"

  # Clean up staging temp dir
  rm -rf "$TMP_DIR"
  return 0
}

# ---------- Incremental Render ----------

vault_render_incremental() {
  local touched_id="$1" cli_vault="${2:-}"
  if ! vault_is_enabled "$cli_vault"; then return 0; fi

  local VAULT lang
  VAULT="$(vault_dir_resolve "$cli_vault")"
  lang="$(vault_get_lang)"
  vault_init_lang_tables "$lang"

  # If vault doesn't exist or marker file missing or language changed: fall back to full render
  if [ ! -d "$VAULT" ] || ! vault_read_marker "$VAULT"; then
    vault_render_full "$cli_vault"
    return $?
  fi
  if [ "$MARKER_LANG" != "$lang" ] || [ "$MARKER_INDEX" != "$INDEX_FILE" ]; then
    vault_render_full "$cli_vault"
    return $?
  fi

  # Ensure subdirectories and inbox exist
  mkdir -p "$VAULT/$DIR_PROJECTS" "$VAULT/$DIR_RECORDS" "$VAULT/$DIR_ISSUES" "$VAULT/$DIR_PRS" "$VAULT/$DIR_INBOX"

  # Collect records to update
  local to_update=()
  [ -n "$touched_id" ] && to_update+=("$touched_id")

  # Find predecessors/successors in supersede chain
  local cur n nxt
  cur="$touched_id"; n=0
  while [ $n -lt 100 ]; do
    nxt="$(printf "SELECT id FROM records WHERE superseded_by=%s;" "$(lit "$cur")" | sqlro 2>/dev/null | head -1)"
    [ -n "$nxt" ] || break
    to_update+=("$nxt")
    cur="$nxt"
    n=$((n+1))
  done
  cur="$touched_id"; n=0
  while [ $n -lt 100 ]; do
    nxt="$(printf "SELECT coalesce(superseded_by,'') FROM records WHERE id=%s;" "$(lit "$cur")" | sqlro 2>/dev/null | head -1)"
    [ -n "$nxt" ] || break
    to_update+=("$nxt")
    cur="$nxt"
    n=$((n+1))
  done

  # Linked records in refs
  local linked_refs
  linked_refs="$(printf "SELECT refs FROM records WHERE id=%s;" "$(lit "$touched_id")" | sqlro 2>/dev/null | jq -r '.[]? | select(startswith("record:")) | sub("^record:"; "")' 2>/dev/null)"
  if [ -n "$linked_refs" ]; then
    while IFS= read -r id; do [ -n "$id" ] && to_update+=("$id"); done <<<"$linked_refs"
  fi

  # Records referencing touched_id
  local referencing
  referencing="$(printf "SELECT id FROM records WHERE refs LIKE '%%\"record:%s\"%%';" "$touched_id" | sqlro 2>/dev/null)"
  if [ -n "$referencing" ]; then
    while IFS= read -r id; do [ -n "$id" ] && to_update+=("$id"); done <<<"$referencing"
  fi

  # Dedup to_update
  local unique_records=() seen_rec=" "
  for id in "${to_update[@]}"; do
    case "$seen_rec" in
      *" $id "*) ;;
      *) seen_rec="$seen_rec$id "; unique_records+=("$id") ;;
    esac
  done

  # Render each affected record and collect its project and issue/PR refs
  local projects_to_update=() seen_proj=" "
  local rec_refs rproj
  for id in "${unique_records[@]}"; do
    vault_render_record_note "$id" "$VAULT/$DIR_RECORDS/$id.md.tmp.$$" && \
      mv -f "$VAULT/$DIR_RECORDS/$id.md.tmp.$$" "$VAULT/$DIR_RECORDS/$id.md"

    rproj="$(printf "SELECT project FROM records WHERE id=%s;" "$(lit "$id")" | sqlro 2>/dev/null)"
    if [ -n "$rproj" ]; then
      case "$seen_proj" in
        *" $rproj "*) ;;
        *) seen_proj="$seen_proj$rproj "; projects_to_update+=("$rproj") ;;
      esac
    fi

    # Render any referenced issue or PR stubs
    rec_refs="$(printf "SELECT refs FROM records WHERE id=%s;" "$(lit "$id")" | sqlro 2>/dev/null | jq -r '.[]?' 2>/dev/null)"
    if [ -n "$rec_refs" ]; then
      local r val slug
      while IFS= read -r r; do
        [ -n "$r" ] || continue
        case "$r" in
          issue:*)
            val="${r#issue:}"
            slug="$(slug_safe_ref "$val")"
            vault_render_issue_stub "$val" "$VAULT/$DIR_ISSUES/$slug.md.tmp.$$" && \
              mv -f "$VAULT/$DIR_ISSUES/$slug.md.tmp.$$" "$VAULT/$DIR_ISSUES/$slug.md"
            ;;
          pr:*)
            val="${r#pr:}"
            slug="$(slug_safe_ref "$val")"
            vault_render_pr_stub "$val" "$VAULT/$DIR_PRS/$slug.md.tmp.$$" && \
              mv -f "$VAULT/$DIR_PRS/$slug.md.tmp.$$" "$VAULT/$DIR_PRS/$slug.md"
            ;;
        esac
      done <<<"$rec_refs"
    fi
  done

  # Render project notes
  local p pslug
  for p in "${projects_to_update[@]}"; do
    pslug="$(slug_safe_project "$p")"
    vault_render_project_note "$p" "$VAULT/$DIR_PROJECTS/$pslug.md.tmp.$$" && \
      mv -f "$VAULT/$DIR_PROJECTS/$pslug.md.tmp.$$" "$VAULT/$DIR_PROJECTS/$pslug.md"
  done

  # Render index note
  vault_render_index_note "$VAULT/$INDEX_FILE.tmp.$$" && \
    mv -f "$VAULT/$INDEX_FILE.tmp.$$" "$VAULT/$INDEX_FILE"

  return 0
}
