vault_get_lang() {
  local l=""
  if [ -f "$CFG/operator.json" ] && command -v jq >/dev/null 2>&1; then
    l="$(jq -r '.chatLanguage // .language // empty' "$CFG/operator.json" 2>/dev/null)"
  fi
  case "$(printf '%s' "$l" | tr '[:upper:]' '[:lower:]')" in
    es|es-*|spanish|español|espanol) printf 'es' ;;
    *) printf 'en' ;;
  esac
}

