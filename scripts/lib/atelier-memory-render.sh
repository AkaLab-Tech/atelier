vault_dir_resolve() {
  local cli_vault="${1:-}"
  if [ -n "$cli_vault" ]; then
    printf '%s' "$cli_vault"
    return 0
  fi
  if [ -n "${ATELIER_MEMORY_VAULT+x}" ]; then
    printf '%s' "$ATELIER_MEMORY_VAULT"
    return 0
  fi
  if [ -n "${ATELIER_CONFIG_DIR:-}" ] && [ "$ATELIER_CONFIG_DIR" != "$HOME/.claude-work" ]; then
    printf '%s/vault' "$ATELIER_CONFIG_DIR"
    return 0
  fi
  printf '%s/Atelier' "$HOME"
}

vault_is_enabled() {
  local cli_vault="${1:-}"
  [ -n "$cli_vault" ] && return 0
  if [ "${ATELIER_MEMORY_VAULT-}" = "off" ]; then return 1; fi
  if [ -f "$CFG/operator.json" ] && command -v jq >/dev/null 2>&1; then
    local v
    v="$(jq -r 'if (.memory | has("vault")) then .memory.vault else empty end' "$CFG/operator.json" 2>/dev/null)"
    [ "$v" = "false" ] || [ "$v" = "off" ] && return 1
  fi
  return 0
}

slug_safe_project() {
  local p="$1" lbl
  [ "$p" = '*' ] && { printf 'global'; return; }
  lbl="$(project_label "$p")"
  printf '%s' "$lbl" | sed 's/[^A-Za-z0-9_.-]/-/g; s/^-*//; s/-*$//'
}

slug_safe_ref() {
  # owner/repo#N -> owner-repo#N
  printf '%s' "$1" | sed 's/\//-/g'
}

vault_read_marker() {
  local marker="$1/.atelier-vault.json"
  MARKER_LANG=""; MARKER_INDEX=""; MARKER_PROJECTS=""; MARKER_RECORDS=""
  MARKER_INBOX=""; MARKER_ISSUES=""; MARKER_PRS=""
  [ -f "$marker" ] || return 1
  command -v jq >/dev/null 2>&1 || return 1
  MARKER_LANG="$(jq -r '.language // empty' "$marker" 2>/dev/null)"
  MARKER_INDEX="$(jq -r '.index // empty' "$marker" 2>/dev/null)"
  MARKER_PROJECTS="$(jq -r '.projects // empty' "$marker" 2>/dev/null)"
  MARKER_RECORDS="$(jq -r '.records // empty' "$marker" 2>/dev/null)"
  MARKER_INBOX="$(jq -r '.inbox // empty' "$marker" 2>/dev/null)"
  MARKER_ISSUES="$(jq -r '.issues // empty' "$marker" 2>/dev/null)"
  MARKER_PRS="$(jq -r '.prs // empty' "$marker" 2>/dev/null)"
  [ -n "$MARKER_INDEX" ]
}

vault_write_marker() {
  local vdir="$1" lang="$2"
  command -v jq >/dev/null 2>&1 || return 0
  jq -n \
    --arg lang "$lang" \
    --arg idx "$INDEX_FILE" \
    --arg prj "$DIR_PROJECTS" \
    --arg rec "$DIR_RECORDS" \
    --arg inb "$DIR_INBOX" \
    --arg iss "$DIR_ISSUES" \
    --arg prs "$DIR_PRS" \
    '{version: 1, language: $lang, index: $idx, projects: $prj, records: $rec, inbox: $inb, issues: $iss, prs: $prs}' \
    > "$vdir/.atelier-vault.json.tmp.$$" && mv -f "$vdir/.atelier-vault.json.tmp.$$" "$vdir/.atelier-vault.json"
}

is_atelier_file() {
  local f="$1" first=""
  [ -f "$f" ] || return 1
  read -r first < "$f" 2>/dev/null || true
  case "$first" in
    '<!-- Generated by atelier — edits here are overwritten; write to '*) return 0 ;;
    *) return 1 ;;
  esac
}

# ---------- Markdown render helpers ----------

vault_render_record_note() { # <id> <target_file>
  local rid="$1" out_file="$2"
  local row type hex_p src hex_ttl hex_bdy hex_qte hex_refs cat hex_cby sby sat clat hex_clby
  row="$(printf "SELECT type||'|'||hex(project)||'|'||source||'|'||hex(title)||'|'||hex(body)||'|'||hex(coalesce(quote,''))||'|'||hex(refs)||'|'||created_at||'|'||hex(created_by)||'|'||coalesce(superseded_by,'')||'|'||coalesce(superseded_at,'')||'|'||coalesce(closed_at,'')||'|'||hex(coalesce(closed_by,''))
 FROM records WHERE id=%s;" "$(lit "$rid")" | sqlro 2>/dev/null)"
  [ -n "$row" ] || return 1
  IFS='|' read -r type hex_p src hex_ttl hex_bdy hex_qte hex_refs cat hex_cby sby sat clat hex_clby <<<"$row"

  local raw_p title body quote refs_json pslug
  raw_p="$(dec "$hex_p")"
  title="$(dec "$hex_ttl")"
  body="$(dec "$hex_bdy")"
  quote="$(dec "$hex_qte")"
  refs_json="$(dec "$hex_refs")"
  pslug="$(slug_safe_project "$raw_p")"

  # Build supersede chain as [[ID]] wikilinks
  local chain="[[$rid]]" cur="$rid" n=0 nxt
  while [ $n -lt 100 ]; do
    nxt="$(printf "SELECT id FROM records WHERE superseded_by=%s;" "$(lit "$cur")" | sqlro 2>/dev/null | head -1)"
    [ -n "$nxt" ] || break
    chain="[[$nxt]] -> $chain"
    cur="$nxt"
    n=$((n+1))
  done
  cur="$rid"; n=0
  while [ $n -lt 100 ]; do
    nxt="$(printf "SELECT coalesce(superseded_by,'') FROM records WHERE id=%s;" "$(lit "$cur")" | sqlro 2>/dev/null | head -1)"
    [ -n "$nxt" ] || break
    chain="$chain -> [[$nxt]]"
    cur="$nxt"
    n=$((n+1))
  done

  # Process references
  local ref_lines="" ref val slug
  if [ -n "$refs_json" ] && [ "$refs_json" != "[]" ]; then
    while IFS= read -r ref; do
      [ -n "$ref" ] || continue
      case "$ref" in
        record:*)
          val="${ref#record:}"
          ref_lines="${ref_lines}- [[$val]]"$'\n'
          ;;
        issue:*)
          val="${ref#issue:}"
          slug="$(slug_safe_ref "$val")"
          ref_lines="${ref_lines}- [[$slug]]"$'\n'
          ;;
        pr:*)
          val="${ref#pr:}"
          slug="$(slug_safe_ref "$val")"
          ref_lines="${ref_lines}- [[$slug]]"$'\n'
          ;;
        file:*)
          val="${ref#file:}"
          ref_lines="${ref_lines}- \`$val\`"$'\n'
          ;;
      esac
    done < <(printf '%s' "$refs_json" | jq -r '.[]?' 2>/dev/null)
  fi

  {
    printf '%s\n\n' "$BANNER"
    printf -- '---\n'
    printf 'id: %s\n' "$rid"
    printf 'type: %s\n' "$type"
    printf 'source: %s\n' "$src"
    printf 'project: %s\n' "$pslug"
    printf 'created: %s\n' "$cat"
    if [ -n "$sby" ]; then
      printf 'superseded_by: %s\n' "$sby"
    else
      printf 'superseded_by: null\n'
    fi
    if [ -n "$clat" ]; then
      printf 'closed: %s\n' "$clat"
    else
      printf 'closed: null\n'
    fi
    printf -- '---\n\n'

    # Title
    printf '# %s\n' "$title"

    # Quote
    if [ -n "$quote" ]; then
      printf '\n'
      printf '%s\n' "$quote" | sed 's/^/> /'
    fi

    # Body
    if [ -n "$body" ]; then
      printf '\n%s\n' "$body"
    fi

    # Project link
    printf '\n## %s\n- [[%s]]\n' "$H_PROJECT" "$pslug"

    # Supersede chain
    printf '\n## %s\n- %s\n' "$H_CHAIN" "$chain"

    # References
    if [ -n "$ref_lines" ]; then
      printf '\n## %s\n%s' "$H_REFS" "$ref_lines"
    fi
  } > "$out_file"
}

vault_render_project_note() { # <raw_proj> <target_file>
  local raw_p="$1" out_file="$2"
  local plbl pslug p_sql
  plbl="$(project_label "$raw_p")"
  pslug="$(slug_safe_project "$raw_p")"
  if [ "$raw_p" = '*' ]; then p_sql="project='*'"; else p_sql="project=$(lit "$raw_p")"; fi

  render_section() { # <heading> <where_cond> <order_limit>
    local heading="$1" cond="$2" ord_lim="$3" rows
    rows="$(printf "SELECT id || '|' || hex(title) FROM records WHERE %s AND %s %s;" "$p_sql" "$cond" "$ord_lim" | sqlro 2>/dev/null)"
    printf '\n## %s\n' "$heading"
    if [ -z "$rows" ]; then
      printf -- '- (none)\n'
      return
    fi
    local line id hex_t t
    while IFS= read -r line; do
      [ -n "$line" ] || continue
      id="${line%%|*}"
      hex_t="${line#*|}"
      t="$(dec "$hex_t" | tr '\r\n' ' ')"
      printf -- '- [[%s]]: %s\n' "$id" "$t"
    done <<<"$rows"
  }

  {
    printf '%s\n\n' "$BANNER"
    printf '# %s\n' "$plbl"
    render_section "$H_OPEN_REQUESTS" "type='request' AND closed_at IS NULL AND superseded_by IS NULL" "ORDER BY created_at DESC, rowid DESC"
    render_section "$H_OPEN_QUESTIONS" "type='question' AND closed_at IS NULL AND superseded_by IS NULL" "ORDER BY created_at DESC, rowid DESC"
    render_section "$H_HELD_ITEMS" "type='held' AND closed_at IS NULL AND superseded_by IS NULL" "ORDER BY created_at DESC, rowid DESC"
    render_section "$H_RECENT_DECISIONS" "type='decision' AND superseded_by IS NULL" "ORDER BY created_at DESC, rowid DESC LIMIT 10"
    render_section "$H_LATEST_DIGEST" "type='digest' AND superseded_by IS NULL" "ORDER BY created_at DESC, rowid DESC LIMIT 1"
    render_section "$H_FACTS_SECTION" "type='fact' AND superseded_by IS NULL" "ORDER BY created_at DESC, rowid DESC"
  } > "$out_file"
}

vault_render_issue_stub() { # <issue_val> (owner/repo#N) <target_file>
  local val="$1" out_file="$2"
  local repo_part="${val%#*}" num_part="${val#*#}"
  local url="https://github.com/${repo_part}/issues/${num_part}"
  local rows
  rows="$(printf "SELECT id, hex(title) FROM records WHERE refs LIKE '%%\"issue:%s\"%%' ORDER BY created_at DESC;" "$val" | sqlro 2>/dev/null)"

  {
    printf '%s\n\n' "$BANNER"
    printf '# %s\n\n' "$val"
    printf '[%s](%s)\n\n' "$url" "$url"
    printf '## %s\n' "$H_MENTIONED"
    if [ -z "$rows" ]; then
      printf -- '- (none)\n'
    else
      local line id hex_t t
